import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
import { predict, vectorize } from '../src/inference.js';

if (!process.argv[2]) throw new Error('Pass the fixture path generated by scripts/make_parity_fixtures.py');
const cases = JSON.parse(readFileSync(process.argv[2], 'utf8'));
for (const family of ['naive_bayes', 'logistic_regression']) {
  const model = JSON.parse(readFileSync(new URL(`../models/${family}.json`, import.meta.url), 'utf8'));
  let maxScoreError = 0;
  for (const testCase of cases) {
    const expected = testCase.expected[family];
    const result = predict(testCase.text, model);
    assert.equal(result.label, expected.label);
    assert.equal(result.borderline, result.knownTerms > 0 && Math.abs(result.score) < 0.5);
    maxScoreError = Math.max(maxScoreError, Math.abs(result.score - expected.score));
    assert.ok(Math.abs(result.score - expected.score) < 1e-10, 'Score mismatch');
    const features = vectorize(testCase.text, model.vectorizer);
    assert.equal(features.length, Object.keys(expected.features).length);
    for (const feature of features) {
      assert.ok(Math.abs(feature.value - expected.features[feature.index]) < 1e-10, 'Feature mismatch');
    }
    const explained = result.offset + result.contributions.reduce((sum, term) => sum + term.contribution, 0);
    assert.ok(Math.abs(explained - result.score) < 1e-10, 'Explanation mismatch');
  }
  console.log(`${family}: ${cases.length} cases passed; max score error ${maxScoreError}. Labels, TF-IDF, and explanations match.`);
}
